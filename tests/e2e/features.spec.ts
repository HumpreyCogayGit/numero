import { expect, test, type Page } from '@playwright/test'
import { chartAction, fixture, freshApp, openSample, tab, typeFormula } from './helpers'

const card = (page: Page, title: string) => page.getByRole('group', { name: new RegExp(`^${title}\\.`) })
const filterChip = (page: Page, text: RegExp) => page.locator('main').getByRole('button', { name: text }).first()

test('calculated measure: create, use in a chart, follows filters', async ({ page }) => {
  const errors = await freshApp(page)
  await openSample(page, 'Seattle Weather')
  await page.getByRole('button', { name: 'New measure' }).click()
  await page.getByRole('textbox', { name: 'Measure name' }).fill('Share of rain')
  await typeFormula(page, '[precipitation]')
  await expect(page.getByText(/Wrap \[Precipitation\] in an aggregate/)).toBeVisible()
  await typeFormula(page, 'SUM([precipitation]) / SUM_ALL([precipitation])')
  await expect(page.getByText(/Overall 1/)).toBeVisible()
  await page.getByRole('button', { name: '×%' }).click()
  await page.getByRole('button', { name: 'Add measure' }).click()

  // use it in the "Sum of Precipitation by Weather" chart
  await card(page, 'Sum of Precipitation by Weather').getByRole('button', { name: 'Edit' }).click()
  await page.getByRole('complementary').getByRole('combobox', { name: 'Aggregation' }).first().selectOption({ label: 'ƒ Share of rain' })
  await page.getByRole('button', { name: 'Show data table' }).first().click({ trial: true }).catch(() => {})
  await page.getByRole('button', { name: 'Done' }).click()
  const c = card(page, 'Sum of Precipitation by Weather')
  await c.getByRole('button', { name: 'Show data table' }).click()
  await expect(c.getByRole('cell', { name: 'Share of rain' }).or(c.getByRole('columnheader', { name: 'Share of rain' }))).toBeVisible()
  expect(errors).toEqual([])
})

test('cross-filtering from a chart and a table, drill-down and drill-up', async ({ page }) => {
  await freshApp(page)
  await openSample(page, 'Seattle Weather')
  // table rows cross-filter
  await card(page, 'Summary by Weather').getByRole('cell', { name: 'snow', exact: true }).click()
  await expect(filterChip(page, /Weather\s*snow/)).toBeVisible()
  await expect(card(page, 'Total records')).toContainText('26')
  await card(page, 'Summary by Weather').getByRole('cell', { name: 'snow', exact: true }).click()
  await expect(card(page, 'Total records')).toContainText('1,461')

  // chart click → filter; click again → cleared
  await chartAction(page, 'Share by Weather', 'click', 0)
  await expect(filterChip(page, /Weather\s*rain/)).toBeVisible()
  await chartAction(page, 'Share by Weather', 'click', 0)
  await expect(filterChip(page, /Weather\s*rain/)).toHaveCount(0)

  // drill-down on a yearly time chart
  await card(page, 'Average of Temp max over time').getByRole('button', { name: 'Edit' }).click()
  await page.getByRole('complementary').getByRole('combobox').filter({ has: page.locator('option[value="year"]') }).first().selectOption('year')
  await page.getByRole('button', { name: 'Done' }).click()
  await chartAction(page, 'Average of Temp max over time', 'dblclick', 1)
  const up = card(page, 'Average of Temp max over time').getByRole('button', { name: /Drill up/ })
  await expect(up).toBeVisible()
  await up.click()
  await expect(up).toHaveCount(0)
})

test('undo and redo across widget, filter and model edits', async ({ page }) => {
  await freshApp(page)
  await openSample(page, 'Palmer Penguins')
  await expect(card(page, 'Share by Species')).toBeVisible()
  const n0 = await page.locator('main [role="group"]').count()
  await card(page, 'Share by Species').getByRole('button', { name: 'More' }).click()
  await page.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(page.locator('main [role="group"]')).toHaveCount(n0 - 1)
  await page.getByRole('button', { name: 'Undo (⌘Z)' }).click()
  await expect(page.locator('main [role="group"]')).toHaveCount(n0)
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(page.locator('main [role="group"]')).toHaveCount(n0 - 1)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.locator('main [role="group"]')).toHaveCount(n0)

  // a model change (column rename) undoes too
  await tab(page, 'Data')
  await page.getByRole('button', { name: /^Species/ }).first().dblclick()
  await page.getByRole('textbox', { name: 'Rename Species' }).fill('Kind')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('columnheader', { name: /Kind/ })).toBeVisible()
  await page.getByRole('button', { name: 'Undo (⌘Z)' }).click()
  await expect(page.getByRole('columnheader', { name: /Species/ })).toBeVisible()
})

