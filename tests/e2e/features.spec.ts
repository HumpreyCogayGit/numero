test('export a dashboard and import it back', async ({ page }) => {
  await freshApp(page)
  await openSample(page, 'Seattle Weather')
  await page.getByRole('button', { name: 'Share' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export dashboard (.json)' }).click()
  const file = await (await download).path()
  // wreck the layout, then restore it from the export
  await page.getByRole('button', { name: 'Add page' }).click()
  await page.getByRole('button', { name: 'Share' }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Import dashboard…' }).click()
  await (await chooser).setFiles(file!)
  await page.getByRole('dialog', { name: 'Replace this dashboard?' }).getByRole('button', { name: 'Import' }).click()
  await expect(page.getByText('Dashboard imported')).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Page 2' })).toHaveCount(0)
  await expect(card(page, 'Total records')).toBeVisible()

  // data export
  await page.getByRole('button', { name: 'Share' }).click()
  const csv = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  expect((await csv).suggestedFilename()).toBe('seattle-weather.csv')
})

